// tools/sync/lib/dsh-instructions.js
//
// dsh 只认 AGENTS.md/CLAUDE.md 文件链（不认 .claude/rules/、小写名、@path 导入）。
// MyRules 的常驻规则因此以「带标记管理块」注入 AGENTS.md：块内是生成物，
// 块外用户内容逐字保留（机制同 gitignore.js 的管理块）。
const fs = require('node:fs');
const path = require('node:path');
const fsutil = require('./fsutil');
const loadManifest = require('./load-manifest');
const paths = require('./paths');

// ~/.dsh/AGENTS.md + 项目链共享 dsh 的 65536 字节基线预算（更宽的文件会被先整体丢弃），
// 超过此值时给出警告。
const BUDGET_WARNING_BYTES = 55 * 1024;

function listMdFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
}

function sectionsFromDir(dir, { prefix = 'myrules-' } = {}) {
  return listMdFiles(dir)
    .filter((f) => f.startsWith(prefix)) // 只装托管产物；legacy 清单里的手工文件不进生成块
    .map((f) => {
      const base = path.basename(f, '.md');
      return {
        topic: base.startsWith(prefix) ? base.slice(prefix.length) : base,
        body: fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s*$/, ''),
      };
    });
}

function buildBlock({ begin, end, sections }) {
  const parts = [
    begin,
    '<!-- generated by myrules sync — edit ~/.myrules/rules/ or .dsh/rules/myrules-*.md, not this block -->',
  ];
  for (const { topic, body } of sections) {
    parts.push(`## myrules: ${topic}\n\n${body}`);
  }
  parts.push(end);
  return parts.join('\n\n');
}

function newlineOf(text) {
  return text.includes('\r\n') ? '\r\n' : '\n';
}

function findBlockRange(text, begin, end) {
  const start = text.indexOf(begin);
  if (start === -1) return null;
  const endStart = text.indexOf(end, start + begin.length);
  if (endStart === -1) return { start, end: null }; // 标记残缺：只有 begin
  return { start, end: endStart + end.length };
}

/**
 * 把生成块写入指令文件的管理块区域；块外内容逐字保留。
 * - 块不存在：追加（空文件不加分隔行）
 * - 块存在且与新块相同：不写
 * - 块被手改（≠ priorHash 且 ≠ 新块）：drifted，跳过；force 才覆盖块内
 * - 块标记残缺（有 begin 无 end）：drifted，跳过（避免叠加出第二个块）
 */
function upsertBlock(agentsFile, block, { begin, end, force = false, priorHash = null } = {}) {
  const existing = fs.existsSync(agentsFile) ? fs.readFileSync(agentsFile, 'utf8') : '';
  const range = findBlockRange(existing, begin, end);

  if (range === null) {
    const nl = newlineOf(existing);
    const separator = existing.length === 0 ? '' : existing.endsWith('\n') ? nl : `${nl}${nl}`;
    fs.writeFileSync(agentsFile, existing + separator + block + nl);
    return { wrote: true, drifted: false, blockHash: fsutil.hashContent(block) };
  }

  if (range.end === null) {
    // 标记残缺：不写、不叠加，按 drift 报告
    return { wrote: false, drifted: true, blockHash: fsutil.hashContent(existing.slice(range.start)) };
  }

  const currentBlock = existing.slice(range.start, range.end);
  const currentHash = fsutil.hashContent(currentBlock);
  if (currentBlock === block) {
    return { wrote: false, drifted: false, blockHash: currentHash };
  }

  const handEdited = priorHash !== null && currentHash !== priorHash;
  if (handEdited && !force) {
    return { wrote: false, drifted: true, blockHash: currentHash };
  }

  fs.writeFileSync(agentsFile, existing.slice(0, range.start) + block + existing.slice(range.end));
  return { wrote: true, drifted: false, blockHash: fsutil.hashContent(block) };
}

/**
 * 项目块：装配 <project>/.dsh/rules/*.md（规则 + method 短规则 + hook 散文），
 * extraSections 追加在规则之后（角色工具表 / 组队规则等）。
 */
function deployProjectInstructions(projectRoot, opts = {}) {
  const manifest = opts.manifest || loadManifest.loadManifest(opts.cacheDir || paths.getCacheDir());
  const dshCfg = manifest.dsh;
  // 旧 manifest（缓存落后于代码）没有 dsh 块：优雅跳过
  if (!dshCfg) return { wrote: false, drifted: false, blockHash: null, blockBytes: 0, agentsFile: null };
  const rulesDir = opts.rulesDir || paths.getDshProjectRulesDir(projectRoot);
  const agentsFile = opts.agentsFile || paths.getDshProjectAgentsFile(projectRoot);
  const sections = [...sectionsFromDir(rulesDir, { prefix: manifest.managedPrefix }), ...(opts.extraSections || [])];
  const block = buildBlock({ begin: dshCfg.blockBegin, end: dshCfg.blockEnd, sections });
  const result = upsertBlock(agentsFile, block, {
    begin: dshCfg.blockBegin,
    end: dshCfg.blockEnd,
    force: Boolean(opts.force),
    priorHash: opts.priorHash || null,
  });
  return { ...result, agentsFile, blockBytes: Buffer.byteLength(block, 'utf8') };
}

/**
 * 用户块：装配 ~/.dsh/rules/*.md（myrules-user-* + 用户 hook 散文）→ ~/.dsh/AGENTS.md
 */
function deployUserInstructions(opts = {}) {
  const manifest = opts.manifest || loadManifest.loadManifest(opts.cacheDir || paths.getCacheDir());
  const dshCfg = manifest.dsh;
  if (!dshCfg) return { wrote: false, drifted: false, blockHash: null, blockBytes: 0, agentsFile: null };
  const homeDir = opts.homeDir || require('node:os').homedir();
  const rulesDir = opts.rulesDir || paths.getDshUserRulesDir(homeDir);
  const agentsFile = opts.agentsFile || paths.getDshUserAgentsFile(homeDir);
  const sections = sectionsFromDir(rulesDir, { prefix: manifest.managedPrefix });
  const block = buildBlock({ begin: dshCfg.blockBegin, end: dshCfg.blockEnd, sections });
  const result = upsertBlock(agentsFile, block, {
    begin: dshCfg.blockBegin,
    end: dshCfg.blockEnd,
    force: Boolean(opts.force),
    priorHash: opts.priorHash || null,
  });
  return { ...result, agentsFile, blockBytes: Buffer.byteLength(block, 'utf8') };
}

function budgetWarning(userBytes, projectBytes) {
  return userBytes + projectBytes > BUDGET_WARNING_BYTES
    ? `MyRules dsh instruction blocks total ${userBytes + projectBytes} bytes; dsh's instruction budget is 65536 and drops broader files first (~/.dsh/AGENTS.md would be dropped before the project AGENTS.md). Trim rules or move detail into skills.`
    : null;
}

module.exports = {
  BUDGET_WARNING_BYTES,
  buildBlock,
  upsertBlock,
  deployProjectInstructions,
  deployUserInstructions,
  sectionsFromDir,
  budgetWarning,
};
